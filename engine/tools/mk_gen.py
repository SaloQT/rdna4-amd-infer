#!/usr/bin/env python3
"""mk_gen.py -- the kernel table of the megakernel (kernels/ie_mk.c).

Reads the KERNEL declarations of kernels/ie_kernels.c and writes a header with:
  - enum MK_<kernel>: the kernel ids of the command list;
  - device (IE_MEGA defined): struct mka_<kernel> (the parameters in kernel
    argument order: the same layout as the kernel arguments of a launch) and
    MK_DISPATCH(kid, args): a switch that calls the kernel body;
  - host: mk_names, mk_nargs, mk_argsz (the size of each parameter: 8 for a
    pointer, 4 for u32 / int / float), so the host packs the void **args of
    a launch into the same bytes.

  tools/mk_gen.py kernels/ie_kernels.c OUT.h SET=kernel,kernel,... ...

Each SET is one build of the megakernel (kernels/ie_mk.c with -DMKS_SET):
the enum and the host tables cover the union of the sets; mk_dispatch has
the cases of the set the build defines, and mk_in_set[s][id] tells the host
which kernels set s has.

A kernel declared KERNEL_LOOP gets a function of its own, mkl_<kernel>, that
runs all the bodies one workgroup takes of a phase (the body inlined in the
loop): its callee-saved registers are saved once per phase instead of once
per body. mk_dispatch_loop calls it; mk_loop_kernel tells ie_mk which kernels
go that way.
"""
import os
import re
import sys

src, out = sys.argv[1], sys.argv[2]
sets = []
loops = set()  # the KERNEL_LOOP / KERNEL_HEAVY / @-tagged kernels
for a in sys.argv[3:]:
    sn, ks_ = a.split("=", 1)
    sk = []
    for raw in ks_.split(","):
        if not raw:
            continue
        if raw.startswith("@"):
            raw = raw[1:]
            loops.add(raw)
        sk.append(raw)
    sets.append((sn, sk))
names = []
for _, ks_ in sets:
    for k in ks_:
        if k not in names:
            names.append(k)


def load_sources(paths):
    seen = set()
    chunks = []

    def visit(p):
        ap = os.path.abspath(p)
        if ap in seen or not os.path.isfile(ap):
            return
        seen.add(ap)
        t = open(ap).read()
        chunks.append(t)
        d = os.path.dirname(ap)
        for inc in re.findall(r'^\s*#\s*include\s+"([^"]+)"', t, re.M):
            if os.path.basename(inc) == "ie_mk_gen.h":
                continue
            cand = os.path.join(d, inc)
            if os.path.isfile(cand):
                visit(cand)

    for p in paths.split(","):
        if p:
            visit(p)
    return "\n".join(chunks)


text = load_sources(src)
sizes4 = {"u32", "int", "float", "unsigned"}


def params(name):
    m = re.search(r"^KERNEL(_HEAVY|_CALL|_LOOP)?\s+" + re.escape(name) + r"\s*\(([^)]*)\)\s*\{", text, re.M)
    if not m:
        sys.exit("mk_gen: no KERNEL %s in %s" % (name, src))
    if m.group(1) in ("_LOOP", "_HEAVY"):
        loops.add(name)
    ps = []
    for p in m.group(2).split(","):
        p = " ".join(p.split())
        pm = re.match(r"(.*?)([A-Za-z_][A-Za-z0-9_]*)$", p)
        ty, nm = pm.group(1).strip(), pm.group(2)
        if "*" in ty:
            sz = 8
        elif ty.replace("const ", "") in sizes4:
            sz = 4
        else:
            sys.exit("mk_gen: %s: parameter type '%s' not handled" % (name, ty))
        ps.append((ty, nm, sz))
    return ps


ks = [(n, params(n)) for n in names]
# kernels/ie_mk.c maps ids >= 30 to the shared profiler event 30 (MK_EV), so
# no set has an id limit any more (the typed raw GEMVs pushed DECODE/MTP past 29).
o = ["/* Generated by tools/mk_gen.py from %s: do not edit. */" % src, "#ifndef IE_MK_GEN_H", "#define IE_MK_GEN_H"]
o.append("enum { " + ", ".join("MK_%s" % n for n, _ in ks) + ", MK_N };")
o.append("#define MK_MAXARGS %d" % max(len(p) for _, p in ks))
o.append("#ifdef IE_MEGA")
for n, ps in ks:
    o.append("struct mka_%s { %s };" % (n, " ".join("%s %s;" % (t, v) for t, v, _ in ps)))
for n, ps in ks:
    if n not in loops:
        continue
    cond = " || ".join("defined(MKS_%s)" % sn for sn, kk in sets if n in kk)
    o.append("#if %s" % cond)
    o.append("static __attribute__((noinline)) void mkl_%s(const G struct mka_%s *p_, u32 v, u32 np, u32 tot, u32 gx, u32 fr) {"
             % (n, n))
    o.append("  const u32 w_ = tid() >> 5;")
    o.append("  for (; v < tot; v += np) {")
    o.append("    if (!fr) barrier();")
    o.append("    if ((tid() & 31u) == 0u) mk_vid[w_][0] = v % gx, mk_vid[w_][1] = v / gx, mk_vid[w_][2] = gx;")
    o.append("    %s(%s);" % (n, ", ".join("p_->%s" % v for _, v, _ in ps)))
    o.append("  }")
    o.append("}")
    o.append("#endif")
o.append("static inline int mk_loop_kernel(u32 kid) {")
o.append("  switch (kid) {")
for n, ps in ks:
    if n not in loops:
        continue
    cond = " || ".join("defined(MKS_%s)" % sn for sn, kk in sets if n in kk)
    o.append("#if %s" % cond)
    o.append("  case MK_%s: return 1;" % n)
    o.append("#endif")
o.append("  default: return 0;")
o.append("  }")
o.append("}")
o.append("static inline void mk_dispatch_loop(u32 kid, const G u8 *a, u32 v, u32 np, u32 tot, u32 gx, u32 fr) {")
o.append("  (void)a, (void)v, (void)np, (void)tot, (void)gx, (void)fr; /* a set without loop kernels */")
o.append("  switch (kid) {")
for n, ps in ks:
    if n not in loops:
        continue
    cond = " || ".join("defined(MKS_%s)" % sn for sn, kk in sets if n in kk)
    o.append("#if %s" % cond)
    o.append("  case MK_%s: mkl_%s((const G struct mka_%s *)a, v, np, tot, gx, fr); break;" % (n, n, n))
    o.append("#endif")
o.append("  default: break;")
o.append("  }")
o.append("}")
o.append("static inline void mk_dispatch(u32 kid, const G u8 *a) {")
o.append("  switch (kid) {")
for n, ps in ks:
    if n in loops:
        continue  # mk_dispatch_loop
    cond = " || ".join("defined(MKS_%s)" % sn for sn, kk in sets if n in kk)
    o.append("#if %s" % cond)
    o.append("  case MK_%s: { const G struct mka_%s *p_ = (const G struct mka_%s *)a; %s(%s); } break;"
             % (n, n, n, n, ", ".join("p_->%s" % v for _, v, _ in ps)))
    o.append("#endif")
o.append("  default: break;")
o.append("  }")
o.append("}")
o.append("#else")
o.append("static const char *const mk_names[MK_N] = {%s};" % ", ".join('"%s"' % n for n, _ in ks))
o.append("static const unsigned char mk_nargs[MK_N] = {%s};" % ", ".join(str(len(p)) for _, p in ks))
o.append("static const unsigned char mk_argsz[MK_N][MK_MAXARGS] = {%s};"
         % ", ".join("{%s}" % ", ".join(str(s) for _, _, s in p) for _, p in ks))
o.append("enum { %s, MK_NSETS };" % ", ".join("MKSET_%s" % sn for sn, _ in sets))
o.append("static const unsigned char mk_in_set[MK_NSETS][MK_N] = {%s};"
         % ", ".join("{%s}" % ", ".join("1" if n in kk else "0" for n, _ in ks) for _, kk in sets))
o.append("#endif")
o.append("#endif")
open(out, "w").write("\n".join(o) + "\n")
