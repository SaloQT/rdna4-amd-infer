"""Write kernels/ie_iq1m_grid8.inc: the IQ1_S grid (kernels/ie_iqraw.inc, ie_rq_iq1s_grid: 8 int8 values of -1, 0 or 1
per entry) as 8 * g + 1 (entries 0 .. 2047) and 8 * g - 1 (entries 2048 .. 4095). An IQ1_M group of 8 weights is
(g + delta) with delta = +-1/8 by the group's sign bit, so its dot with 8 activations is dot(8 g +- 1, x) / 8: the
_tr8 kernel reads that from one table entry instead of adding the activations' sum to 8 * dot(g, x) for each token.
usage: python tools/gen_iq1m_grid8.py"""
import os
import re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, 'kernels', 'ie_iqraw.inc'), encoding='utf-8').read()
body = re.search(r'ie_rq_iq1s_grid\[2048\] = \{(.*?)\};', src, re.S).group(1)
grid = [int(v, 16) for v in re.findall(r'0x[0-9a-fA-F]+', body)]
assert len(grid) == 2048, len(grid)


def entry(g, d):
    out = 0
    for i in range(8):
        b = (g >> (8 * i)) & 255
        v = b - 256 if b > 127 else b
        assert v in (-1, 0, 1), hex(g)
        out |= ((8 * v + d) & 255) << (8 * i)
    return out


vals = [entry(g, 1) for g in grid] + [entry(g, -1) for g in grid]
lines = ['/* generated by tools/gen_iq1m_grid8.py from ie_rq_iq1s_grid: 8 g + 1, then 8 g - 1 (int8 bytes) */',
         'static const ie_rq_u64 ie_rq_iq1m_grid8[4096] = {']
for i in range(0, 4096, 4):
    lines.append('    ' + ', '.join('0x%016x' % v for v in vals[i:i + 4]) + ',')
lines.append('};')
open(os.path.join(root, 'kernels', 'ie_iq1m_grid8.inc'), 'w', newline='\n').write('\n'.join(lines) + '\n')
print('wrote kernels/ie_iq1m_grid8.inc (4096 entries)')
